def derive_subcategory(category: str, title: str) -> str:
    text = title or ""
    for subcategory, keywords in SUBCATEGORY_RULES.get(category or "", []):
        if any(keyword in text for keyword in keywords):
            return subcategory
    return FALLBACK_SUBCATEGORY